"""
Credit scoring: from raw applicant data to a validated probability-of-default model.

Two models are compared on the same data:
  1. The industry-standard scorecard: Weight-of-Evidence (WoE) binning + logistic regression,
     converted to points (interpretable, monotone, accepted by regulators and auditors).
  2. A gradient-boosting classifier (non-linear, higher accuracy, harder to explain).

Validation follows bank model-risk practice: discrimination (AUC, Gini, KS), calibration
(predicted vs observed default rates), stability across samples (PSI), and a rating master
scale that maps PDs to grades.

The data are synthetic: 30,000 loan applications with realistic relationships, non-linear
effects and missing values, generated by `generate_applications`.

Author: Adam Rejeb
"""
from __future__ import annotations

import numpy as np
import pandas as pd
from sklearn.metrics import roc_auc_score, roc_curve


# ---------------------------------------------------------------- synthetic data
def generate_applications(n=30_000, seed=0) -> pd.DataFrame:
    rng = np.random.default_rng(seed)
    age = rng.integers(21, 70, n)
    income = np.round(rng.lognormal(np.log(38_000), 0.45, n), -2)
    employment = rng.choice(["permanent", "temporary", "self-employed", "unemployed"], n, p=[0.66, 0.16, 0.14, 0.04])
    history_years = np.clip(age - 18 - rng.exponential(4, n), 0, None).round(1)
    loan_amount = np.round(np.clip(rng.lognormal(np.log(12_000), 0.6, n), 1_000, 80_000), -2)
    dti = np.clip(rng.beta(2.2, 6, n) + loan_amount / income * 0.08, 0, 1.2).round(3)        # debt-to-income
    utilisation = np.clip(rng.beta(2, 3, n) + 0.15 * (dti > 0.45), 0, 1).round(3)
    late_payments = rng.poisson(0.25 + 1.5 * utilisation**2, n)
    home = rng.choice(["owner", "mortgage", "renter"], n, p=[0.25, 0.40, 0.35])

    # true (hidden) default model: non-linear in age and utilisation, with an interaction
    logit = (-4.9 + 2.4 * dti + 2.2 * (utilisation - 0.5) ** 2 + 1.6 * utilisation + 0.55 * late_payments
             - 0.35 * np.log(income / 38_000) - 0.04 * np.minimum(history_years, 20)
             + 0.0012 * (age - 40) ** 2 - 0.01 * (age - 40)
             + np.select([employment == "temporary", employment == "self-employed", employment == "unemployed"], [0.45, 0.35, 1.3], 0.0)
             + np.where(home == "renter", 0.25, 0.0) + 0.6 * dti * (employment == "self-employed"))
    default = rng.random(n) < 1 / (1 + np.exp(-logit))

    df = pd.DataFrame({"age": age, "income": income, "employment": employment, "home": home, "history_years": history_years,
                       "loan_amount": loan_amount, "dti": dti, "utilisation": utilisation, "late_payments": late_payments,
                       "default": default.astype(int)})
    missing = rng.random(n) < 0.06
    df.loc[missing, "income"] = np.nan                                   # real files have gaps
    return df


# ---------------------------------------------------------------- Weight of Evidence
class WoEEncoder:
    """Bins each feature and replaces it by its Weight of Evidence:
        WoE(bin) = ln( share of non-defaulters in bin / share of defaulters in bin )
    A positive WoE marks a safer-than-average bin. Missing values get their own bin."""

    def __init__(self, n_bins=6, smoothing=0.5):
        self.n_bins, self.smoothing = n_bins, smoothing
        self.tables, self.edges = {}, {}

    def _bin(self, col, x):
        if col in self.edges:
            b = pd.cut(x, self.edges[col], include_lowest=True).astype(str)
        else:
            b = x.astype(str)
        return b.where(x.notna(), "missing")

    def fit(self, X: pd.DataFrame, y: pd.Series):
        for col in X.columns:
            x = X[col]
            if pd.api.types.is_numeric_dtype(x) and x.nunique() > self.n_bins:
                values = np.sort(x.dropna().unique())
                if np.allclose(values, np.round(values)) and len(values) <= 15:
                    # count variable (e.g. late payments): one bin per value, last bin open-ended
                    qs = np.concatenate([[-np.inf], values[: self.n_bins - 1] + 0.5, [np.inf]])
                else:
                    qs = np.unique(np.nanquantile(x, np.linspace(0, 1, self.n_bins + 1)))
                    qs[0], qs[-1] = -np.inf, np.inf
                self.edges[col] = qs
            bins = self._bin(col, x)
            stats = pd.DataFrame({"bin": bins, "y": y.values}).groupby("bin")["y"].agg(["count", "sum"])
            bad, good = stats["sum"] + self.smoothing, stats["count"] - stats["sum"] + self.smoothing
            dist_bad, dist_good = bad / bad.sum(), good / good.sum()
            stats["default_rate"] = stats["sum"] / stats["count"]
            stats["woe"] = np.log(dist_good / dist_bad)
            stats["iv_part"] = (dist_good - dist_bad) * stats["woe"]
            self.tables[col] = stats
        return self

    def transform(self, X: pd.DataFrame) -> pd.DataFrame:
        out = {}
        for col in X.columns:
            out[col] = self._bin(col, X[col]).map(self.tables[col]["woe"]).fillna(0.0).astype(float)
        return pd.DataFrame(out, index=X.index)

    def information_values(self) -> pd.Series:
        """IV < 0.02 useless, 0.02-0.1 weak, 0.1-0.3 medium, > 0.3 strong predictor."""
        return pd.Series({c: t["iv_part"].sum() for c, t in self.tables.items()}).sort_values(ascending=False)


# ---------------------------------------------------------------- scorecard points
def scorecard_points(coefs: dict, intercept: float, encoder: WoEEncoder, base_score=600, base_odds=50, pdo=20):
    """Points per bin, the format used by credit officers.
    Score = offset + factor x ln(odds good:bad); `pdo` points double the odds."""
    factor = pdo / np.log(2)
    offset = base_score - factor * np.log(base_odds)
    n = len(coefs)
    rows = []
    for col, beta in coefs.items():
        for b, woe in encoder.tables[col]["woe"].items():
            # the model predicts log-odds of default = intercept + sum(beta x WoE); good:bad odds is the negative
            points = -(beta * woe + intercept / n) * factor + offset / n
            rows.append({"feature": col, "bin": b, "woe": woe, "points": points})
    return pd.DataFrame(rows)


def score_from_pd(pd_, base_score=600, base_odds=50, pdo=20):
    factor = pdo / np.log(2)
    return base_score - factor * np.log(base_odds) + factor * np.log((1 - pd_) / pd_)


# ---------------------------------------------------------------- validation
def gini(y, p):
    return 2 * roc_auc_score(y, p) - 1


def ks_statistic(y, p):
    fpr, tpr, _ = roc_curve(y, p)
    return float(np.max(tpr - fpr))


def calibration_table(y, p, n_bins=10):
    df = pd.DataFrame({"y": np.asarray(y), "p": np.asarray(p)})
    df["bucket"] = pd.qcut(df["p"], n_bins, labels=False, duplicates="drop")
    return df.groupby("bucket").agg(predicted_pd=("p", "mean"), observed_dr=("y", "mean"), count=("y", "size"))


def population_stability_index(expected_scores, actual_scores, n_bins=10):
    """PSI < 0.1 stable, 0.1-0.25 monitor, > 0.25 the population has shifted."""
    edges = np.unique(np.quantile(expected_scores, np.linspace(0, 1, n_bins + 1)))
    edges[0], edges[-1] = -np.inf, np.inf
    e = np.histogram(expected_scores, edges)[0] / len(expected_scores)
    a = np.histogram(actual_scores, edges)[0] / len(actual_scores)
    e, a = np.clip(e, 1e-6, None), np.clip(a, 1e-6, None)
    return float(((a - e) * np.log(a / e)).sum())


MASTER_SCALE = [("1 (AAA-AA)", 0.0, 0.0005), ("2 (A)", 0.0005, 0.0015), ("3 (BBB)", 0.0015, 0.005),
                ("4 (BB+)", 0.005, 0.015), ("5 (BB-)", 0.015, 0.035), ("6 (B)", 0.035, 0.08),
                ("7 (B-)", 0.08, 0.20), ("8 (CCC)", 0.20, 1.0)]


def assign_grade(pd_):
    labels = np.empty(len(pd_), dtype=object)
    for name, lo, hi in MASTER_SCALE:
        labels[(pd_ >= lo) & (pd_ < hi)] = name
    return labels
